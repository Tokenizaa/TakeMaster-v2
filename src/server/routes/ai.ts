import { Request, Response, Router } from 'express';
import { resolveRequestAuthContext } from '../auth';
import {
  generateEditorialDiagnosis,
  generateEditorialResearch,
  generateSmartOutline,
  generateStudioScript,
  generateFollowUpRepiques,
  generatePlannedShorts,
  generateEditorScriptSynthesis,
  generateContextualAssist,
  generateProgramEditorialIdentity,
  generateProgramPitchSuggestions
} from '../ai';
import { assertOrganizationMember } from '../authorization';
import { AppError } from '../../domain/validation';

const router = Router();

router.post('/diagnosis', async (req: Request, res: Response) => {
  try {
    const ctx = await resolveRequestAuthContext(req);
    await assertOrganizationMember(ctx.userId, ctx.organizationId);
    const diagnosis = await generateEditorialDiagnosis(req.body);
    res.json(diagnosis);
  } catch (error) {
    if (error instanceof AppError) {
      res.status(error.statusCode).json({ code: error.code, message: error.message });
    } else {
      res.status(500).json({ code: 'INTERNAL_ERROR', message: 'Erro interno.' });
    }
  }
});

